export function normalizeAssistantPathname(value?: string | null) {
  if (!value || typeof value !== "string") return "/";
  const pathname = value.split(/[?#]/, 1)[0].trim();
  if (!pathname.startsWith("/") || pathname.length > 180) return "/";
  return pathname.replace(/\/{2,}/g, "/");
}

export function getAssistantPageContext(value?: string | null): AssistantPageContext {
  const pathname = normalizeAssistantPathname(value);
  return contexts.find(({ match }) => match(pathname))?.value ?? generalContext;
}

export function assistantSuggestionsForPage(
  query: string,
  pathname: string | null | undefined,
  fallback: string[],
) {
  const context = getAssistantPageContext(pathname);
  const text = query.toLowerCase();
  const asksAboutPage = /калькулятор|как пользоваться|поле|формат|результат|dxf|step|stp|dwg|pdf|загруз|файл|черт[её]ж|исходн|что нужно|какие.*данн|подготов.*заяв|для расч[её]т|длина реза|заготов|масса/.test(text);
  return context.id !== "general" && asksAboutPage ? context.suggestions : fallback;
}

