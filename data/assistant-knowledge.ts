function includesAny(text: string, words: string[]) {
  return words.some((word) => text.includes(word));
}

export function assistantSuggestions(query: string) {
  const text = query.toLowerCase();
  if (includesAny(text, ["цен", "стоим", "рассчит", "заказ", "заявк"])) {
    return ["Передать исходные данные", "Какие файлы приложить?", "Что влияет на стоимость?"];
  }
  if (includesAny(text, ["порош", "покрас", "ral", "цвет", "дробест", "лазерная чист", "лазерная очист"])) {
    return ["Как подготовить изделие?", "Какие данные нужны?", "Передать заявку"];
  }
  if (includesAny(text, ["лазер", "резк", "гибк", "свар", "технолог", "производ"])) {
    return ["Полный технологический цикл", "Как подготовить чертёж?", "Передать задачу инженеру"];
  }
  if (includesAny(text, ["кондиц", "корзин", "экран", "кронштейн"])) {
    return ["Какие размеры нужны?", "Варианты исполнения", "Передать заявку"];
  }
  return ["Рассчитать изделие", "Возможности производства", "Передать задачу инженеру"];
}

