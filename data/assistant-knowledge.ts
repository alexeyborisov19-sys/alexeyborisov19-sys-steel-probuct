function productKnowledge() {
  return products.map((product) => [
    product.title,
    product.lead,
    `Применение: ${product.applications.join(", ")}.`,
    `Преимущество: ${product.advantage}`,
    ...(product.specs ?? []).map((spec) => `${spec.label}: ${spec.value}`),
  ].join(" ")).join("\n");
}

function solutionKnowledge() {
  const mainDirections = solutions.map((solution) =>
    `${solution.title}: ${solution.text} Изделия: ${solution.items.join(", ")}.`,
  ).join("\n");

  const details = solutionDetails.map((solution) => [
    `${solution.title}. ${solution.introduction}`,
    ...solution.items.map((item) =>
      `${item.title}: ${item.description} Применение: ${item.application}.`,
    ),
    `Для проработки обычно требуются: ${solution.requirements.join("; ")}.`,
  ].join("\n")).join("\n");

  return `${mainDirections}\n${details}`;
}

