import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { chromium } from '@playwright/test';
const base=(process.env.BIM_AUDIT_BASE_URL||'http://127.0.0.1:8080').replace(/\/$/,'');
const out=path.resolve(process.env.BIM_SIZING_OUTPUT_DIR||'artifacts/cassette-parametric');
await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true});
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 const response=await page.goto(base+'/bim/metallokassety-parametric/index.html',{waitUntil:'networkidle'});
 assert.equal(response.status(),200);
 await page.locator('body[data-ready="true"]').waitFor({timeout:60000});
 assert.equal(await page.locator('#model option').count(),15);
 const renderer=await page.locator('#canvas').getAttribute('data-renderer');
 const initial=Number(await page.locator('#dim-0').inputValue());
 await page.locator('#dim-0').fill(String(initial+100));
 assert(await page.locator('#download').isDisabled());
 await page.locator('#apply').click();
 assert(await page.locator('#download').isEnabled());
 let downloadPromise=page.waitForEvent('download');await page.locator('#download').click();
 let download=await downloadPromise;await download.saveAs(path.join(out,'browser-export.ifc'));
 const exported=await fs.readFile(path.join(out,'browser-export.ifc'),'utf8');
 assert(exported.includes('IFCTRIANGULATEDFACESET'));
 downloadPromise=page.waitForEvent('download');await page.locator('#save-project').click();
 download=await downloadPromise;await download.saveAs(path.join(out,'browser-settings.json'));
 const saved=JSON.parse(await fs.readFile(path.join(out,'browser-settings.json'),'utf8'));
 assert(Math.abs(saved.dimensions[0]-initial-100)<.002);
 await page.locator('#dim-0').fill('0');await page.locator('#apply').click();
 assert(await page.locator('#download').isDisabled());assert(await page.locator('#error').isVisible());
 await page.locator('#reset').click();
 await page.locator('#load-project').setInputFiles(path.join(out,'browser-settings.json'));
 await page.locator('#pending:not([hidden])').waitFor();
 assert(Math.abs(Number(await page.locator('#dim-0').inputValue())-initial)<.002);
 await page.locator('#confirm-import').click();
 await page.locator('body[data-ready="true"]').waitFor();
 assert(Math.abs(Number(await page.locator('#dim-0').inputValue())-initial-100)<.002);
 const ids=await page.locator('#model option').evaluateAll(options=>options.map(option=>option.value));
 for(const id of ids){
  await page.locator('#model').selectOption(id);
  await page.locator(`body[data-ready="true"][data-model="${id}"]`).waitFor({timeout:60000});
  assert(await page.locator('#download').isEnabled(),id);
  assert.equal(await page.locator('#canvas').getAttribute('data-rendered'),'true');
  if(['SP-TRIM-12','SP-TRIM-15'].includes(id))assert.notEqual(await page.locator('#dim-1').getAttribute('readonly'),null);
 }
 await page.locator('#model').selectOption('SP-CAS-06');
 await page.locator('body[data-ready="true"][data-model="SP-CAS-06"]').waitFor();
 await page.screenshot({path:path.join(out,'desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile horizontal overflow');
 await page.screenshot({path:path.join(out,'mobile.png'),fullPage:true});
 const fallback=await browser.newPage({viewport:{width:390,height:844}});
 fallback.on('pageerror',error=>errors.push(error.message));
 await fallback.addInitScript(()=>{const original=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(type,...args){return type.includes('webgl')?null:original.call(this,type,...args);};});
 await fallback.goto(base+'/bim/metallokassety-parametric/index.html',{waitUntil:'networkidle'});
 await fallback.locator('body[data-ready="true"]').waitFor({timeout:60000});
 assert.equal(await fallback.locator('#canvas').getAttribute('data-renderer'),'Canvas2D');
 assert(await fallback.locator('#download').isEnabled());
 assert.deepEqual(errors,[]);
 const report={base,modelCount:ids.length,renderer,allModelsRendered:true,resizedIfcDownloaded:true,settingsRoundTrip:true,invalidInputBlocked:true,mobileNoOverflow:true,canvasFallback:true,pageErrors:errors,formSubmissions:0};
 await fs.writeFile(path.join(out,'browser-report.json'),JSON.stringify(report,null,2));console.log(report);
}finally{await browser.close();}
