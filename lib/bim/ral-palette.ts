const popular = new Set(["1015","3005","5005","6005","7016","7024","7035","8017","9003","9005","9006","9016"]);
export function filterRalPalette(query: string, family: string) {
  const normalized = query.toLocaleLowerCase("ru").replace(/ral\s*/g, "").replaceAll("ё","е").trim();
  // Search spans the whole palette, even if a family was previously selected.
  return ralPalette.filter(c=> normalized ? `${c.code} ${c.name}`.toLocaleLowerCase("ru").replaceAll("ё","е").includes(normalized)
    : family === "popular" ? popular.has(c.code) : family === "all" || c.code.startsWith(family));
}
